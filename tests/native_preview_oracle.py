#!/usr/bin/env python3
"""Independent byte oracle for the complex native-preview fixture.

Call with the CPV output path. All field values below are literal fixture facts,
not generated by the producer or the Rust CPV encoder. This checks the complete
wire image, including non-rendered records, reordered records and arc points.
"""
import pathlib
import sys
import hashlib
import json
import tempfile


def h(s):
    return bytes.fromhex(s)


HEADER = h('43505631 01000000 05000000 02000000 50000000 01000000 00000000 00000000')
DUMMY = h('''
    00000000 00000000 00000000 00000000 00000000 00000000 00000000
    00000000 00000000 00000000 00000000 00000000 00000000
    00000000 ffffffff 00000000 00000000 00000000 00000000 ffffffff
''')
TRAVEL = h('''
    0000a03f 00000080 0000803e 00000000 00000000 00000000 00000000
    00000000 00000000 00000000 00000000 00000000 00000000
    04000000 ffffffff 00000000 00000000 08000001 00000000 ffffffff
''')
SEAM = h('''
    00000000 00000000 00000000 00000000 00000000 00000000 00000000
    00000000 00000000 00000000 00000000 00000000 00000000
    04000000 ffffffff 00000000 00000000 03010000 00000000 ffffffff
''')
PAUSE = h('''
    00000000 00000000 00000000 00000000 00000000 00000000 00000000
    00000000 00000000 00000000 00000000 00000000 00000000
    05000000 ffffffff 00000000 00000000 06130000 00000000 ffffffff
''')
ARC = h('''
    00004040 00000040 0000803e 0000003f 0000803e 00002a42 0000003e
    00005243 00002842 00004841 0000f040 00001041 0000803e
    05000000 ffffffff 00000000 02000000 0a020202 0000003f 07000000
''')
ARCS = h('00001040 0000c03f 0000803e 00004040 00000040 0000803e')
PA_FLAGS = h('01 01 01 01 03')
EXPECTED = HEADER + DUMMY + TRAVEL + SEAM + PAUSE + ARC + ARCS + PA_FLAGS


def verify(path):
    got = pathlib.Path(path).read_bytes()
    if got != EXPECTED:
        for i, (a, b) in enumerate(zip(got, EXPECTED)):
            if a != b:
                raise AssertionError(f'CPV byte {i}: {a:02x} != {b:02x}')
        raise AssertionError(f'CPV length {len(got)} != {len(EXPECTED)}')


def unique_pairs(pairs):
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise AssertionError(f'duplicate JSON key: {key}')
        obj[key] = value
    return obj


def verify_mapping(path, processor_map=None):
    got = json.loads(pathlib.Path(path).read_text(), object_pairs_hook=unique_pairs)
    expected = {
        'schema': 'corvus-native-preview-map/1',
        'executionSha256': 'a' * 64,
        'sourceSha256': '28ee975e2aaf287a9658745baa2d00818fac21f84aa6c346f4c6337a65b9bec2',
        'sourceBytes': '12',
        'processorMapSha256': 'c' * 64,
        'processorMapBytes': '34',
        'cpvSha256': hashlib.sha256(EXPECTED).hexdigest(),
        'cpvBytes': '461',
        'records': [
            {'stableId': '0', 'finalIndex': '0', 'ordinal': '0', 'kind': 'DUMMY',
             'primitivePotential': 'SEED_OR_NON_SEGMENT', 'arcPoints': '0', 'seed': True, 'synthetic': False, 'dummy': True, 'segmentCandidate': False, 'noGeometry': True},
            {'stableId': '1', 'finalIndex': '1', 'ordinal': '1', 'kind': 'OBSERVED',
             'primitivePotential': 'SEGMENT_MAY_BE_FILTERED', 'arcPoints': '0', 'seed': False, 'synthetic': False, 'dummy': False, 'segmentCandidate': True, 'noGeometry': False},
            {'stableId': '3', 'finalIndex': '2', 'ordinal': '2', 'kind': 'SYNTHETIC_PREVIOUS',
             'primitivePotential': 'SEED_OR_NON_SEGMENT', 'arcPoints': '0', 'seed': False, 'synthetic': True, 'dummy': False, 'segmentCandidate': False, 'noGeometry': False},
            {'stableId': '2', 'finalIndex': '3', 'ordinal': '3', 'kind': 'SYNTHETIC_EVENT',
             'primitivePotential': 'SEED_OR_NON_SEGMENT', 'arcPoints': '0', 'seed': False, 'synthetic': True, 'dummy': False, 'segmentCandidate': False, 'noGeometry': False},
            {'stableId': '4', 'finalIndex': '4', 'ordinal': '4', 'kind': 'OBSERVED',
             'primitivePotential': 'SEGMENT_MAY_BE_FILTERED', 'arcPoints': '2', 'seed': False, 'synthetic': False, 'dummy': False, 'segmentCandidate': True, 'noGeometry': False},
        ],
    }
    if processor_map is not None:
        map_bytes = pathlib.Path(processor_map).read_bytes()
        expected['processorMapSha256'] = hashlib.sha256(map_bytes).hexdigest()
        expected['processorMapBytes'] = str(len(map_bytes))
        import native_processor_move_map_oracle as map_oracle
        expected_records = map_oracle.literal_fixtures()['complex'][1]
        actual_records = [json.loads(line, object_pairs_hook=unique_pairs) for line in map_bytes.splitlines()]
        map_oracle.compare(actual_records, expected_records, 'native processor map')
    if got != expected:
        raise AssertionError(f'preview mapping mismatch\nactual: {got!r}\nexpected: {expected!r}')


def main():
    if len(sys.argv) not in (3, 4):
        raise SystemExit('usage: native_preview_oracle.py output.cpv output.json [processor-map.jsonl]')
    assert len(HEADER) == 32 and all(len(x) == 80 for x in (DUMMY, TRAVEL, SEAM, PAUSE, ARC))
    assert len(EXPECTED) == 461
    verify(sys.argv[1])
    verify_mapping(sys.argv[2], sys.argv[3] if len(sys.argv) == 4 else None)
    # Independent verifier rejects altered bytes, reordered records, and a stale map.
    with tempfile.TemporaryDirectory() as directory:
        temp = pathlib.Path(directory)
        altered = bytearray(EXPECTED); altered[32 + 80 + 1] ^= 1
        path = temp / 'altered.cpv'; path.write_bytes(altered)
        try: verify(path)
        except AssertionError: pass
        else: raise AssertionError('tampered CPV accepted')
        reordered = EXPECTED[:112] + EXPECTED[192:272] + EXPECTED[112:192] + EXPECTED[272:]
        path.write_bytes(reordered)
        try: verify(path)
        except AssertionError: pass
        else: raise AssertionError('reordered CPV accepted')
        mapping = json.loads(pathlib.Path(sys.argv[2]).read_text())
        mapping['processorMapSha256'] = 'd' * 64
        path = temp / 'stale.json'; path.write_text(json.dumps(mapping))
        try: verify_mapping(path, sys.argv[3] if len(sys.argv) == 4 else None)
        except AssertionError: pass
        else: raise AssertionError('stale processor map identity accepted')
    print('native preview literal CPV bytes and mapping: OK')


if __name__ == '__main__':
    main()
